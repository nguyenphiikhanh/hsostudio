import {test,expect} from '@playwright/test'

test('on-screen frame inspector pauses, seeks and marks source sheets in all four directions without downloads',async({page})=>{
 const errors=[],downloads=[];page.on('pageerror',e=>errors.push(e.message));page.on('download',d=>downloads.push(d))
 await page.goto('/character-lab')
 await expect(page.getByLabel('Phái nhân vật',{exact:true})).toBeVisible({timeout:30000})
 await page.getByRole('tab',{name:'Animation',exact:true}).click()
 await page.getByRole('button',{name:'Soi asset theo frame',exact:true}).click()
 const panel=page.getByRole('region',{name:'Soi asset theo frame',exact:true})
 await expect(panel).toBeVisible();await expect(page.getByRole('button',{name:'Phát animation',exact:true})).toBeVisible()
 const slider=page.getByLabel('Frame soi asset',{exact:true})
 await slider.fill('0');await expect(panel).toHaveAttribute('data-rendered-frame','0')
 const canvas=page.getByLabel('Nhân vật ghép theo frame',{exact:true})
 const first=await canvas.evaluate(c=>c.toDataURL())
 await slider.fill('2');await expect(panel).toHaveAttribute('data-rendered-frame','2')
 await expect.poll(()=>canvas.evaluate(c=>c.toDataURL())).not.toBe(first)
 const stopped=await canvas.evaluate(c=>c.toDataURL());await page.waitForTimeout(200);expect(await canvas.evaluate(c=>c.toDataURL())).toBe(stopped)
 for(const direction of ['down','up','left','right']){
  await page.getByLabel('Hướng soi asset',{exact:true}).selectOption(direction)
  await expect(panel).toHaveAttribute('data-rendered-direction',direction)
  expect(await panel.locator('.frame-source-sheet').count()).toBeGreaterThan(3)
  for(const sheet of await panel.locator('.frame-source-sheet canvas').all()){
   const data=await sheet.evaluate(c=>({width:c.width,height:c.height,crops:JSON.parse(c.dataset.crops),pixels:Array.from(c.getContext('2d').getImageData(0,0,c.width,c.height).data)}))
   for(const r of data.crops){expect(r.x).toBeGreaterThanOrEqual(0);expect(r.y).toBeGreaterThanOrEqual(0);expect(r.x+r.width).toBeLessThanOrEqual(data.width);expect(r.y+r.height).toBeLessThanOrEqual(data.height)}
   expect(data.pixels.some((v,i)=>i%4===3&&v>0)).toBe(true)
  }
 }
 await expect(panel).toContainText('lật ngang')
 await page.getByLabel('Sheet đúng kích thước pixel',{exact:true}).check()
 await expect(panel.locator('.frame-source-sheet canvas').first()).toHaveClass(/frame-sheet-native/)
 await page.getByLabel('Trạng thái nhân vật',{exact:true}).selectOption('walk')
 await slider.fill('5');await expect(panel).toHaveAttribute('data-rendered-frame','5')
 await expect(page.locator('.frame-status')).toContainText('Đi bộ 6/10')
 await page.getByRole('button',{name:'Frame trước',exact:true}).click();await expect(panel).toHaveAttribute('data-rendered-frame','4')
 await page.getByRole('button',{name:'Frame sau',exact:true}).click();await expect(panel).toHaveAttribute('data-rendered-frame','5')
 await page.getByRole('button',{name:'Phát khi soi frame',exact:true}).click()
 await expect.poll(()=>panel.getAttribute('data-rendered-frame')).not.toBe('5')
 await page.getByRole('button',{name:'Dừng soi frame',exact:true}).click()
 await page.screenshot({path:'/tmp/hso-frame-asset-inspector.png',fullPage:true})
 await page.getByRole('link',{name:'Map',exact:true}).click();await page.getByRole('link',{name:'Character Lab',exact:true}).click()
 await expect(panel).toBeVisible();await expect(panel.locator('[role=alert]')).toHaveCount(0)
 await page.getByRole('button',{name:'Đóng soi asset',exact:true}).click();await expect(panel).toHaveCount(0)
 expect(downloads).toHaveLength(0);expect(errors).toEqual([])
})

test('attack inspector uses WPS and skill-effect crops including mounted/hidden pieces',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/character-lab');await expect(page.getByLabel('Vũ khí thường HSO',{exact:true})).toBeVisible({timeout:30000})
 await page.getByLabel('Vũ khí thường HSO',{exact:true}).selectOption('0')
 await page.getByRole('tab',{name:'Animation',exact:true}).click()
 await page.getByLabel('Trạng thái nhân vật',{exact:true}).selectOption('attack')
 await page.getByRole('button',{name:'Soi asset theo frame',exact:true}).click()
 const panel=page.getByRole('region',{name:'Soi asset theo frame',exact:true}),slider=page.getByLabel('Frame soi asset',{exact:true})
 await slider.fill('4');await expect(panel).toHaveAttribute('data-rendered-frame','4')
 await expect(panel).toContainText('wps')
 await page.getByLabel('Kỹ năng tấn công',{exact:true}).selectOption('1')
 await slider.fill('12');await expect(panel).toHaveAttribute('data-rendered-frame','12')
 await expect(panel).toContainText('Hiệu ứng')
 await expect(panel.locator('[role=alert]')).toHaveCount(0)
 const accuracy=await page.evaluate(async()=>{
  const {frameAssetGroups}=await import('/src/lib/frameAssets.js')
  const layer={name:'test',asset:{image:'same',width:100,height:100,density:2},sx:2,sy:3,w:4,h:5,x:7,y:8,visible:true,flipX:true,renderDepth:9}
  const r=frameAssetGroups([layer,{...layer,visible:false},{...layer,sx:100}])
  return {crop:r.groups[0].entries[0].rectPx,hidden:r.hidden.length,invalid:r.invalid.length,flip:r.groups[0].entries[0].flipX,depth:r.groups[0].entries[0].depth}
 })
 expect(accuracy).toEqual({crop:{x:4,y:6,width:8,height:10},hidden:1,invalid:1,flip:true,depth:9})
 await page.getByRole('tab',{name:'Trang bị',exact:true}).click()
 await page.getByLabel('Thú cưỡi',{exact:true}).selectOption('0')
 await page.getByRole('tab',{name:'Animation',exact:true}).click()
 await slider.fill('0');await expect(panel).toHaveAttribute('data-rendered-frame','0')
 await expect(panel).toContainText('mount')
 await expect(panel.locator('[role=alert]')).toHaveCount(0)
 expect(errors).toEqual([])
})
