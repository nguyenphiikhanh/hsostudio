import {test,expect} from '@playwright/test'

test('desktop workspaces keep one main preview, contextual tabs and route-specific actions',async({page})=>{
 test.setTimeout(90000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('/character-lab')
 await expect(page.getByLabel('Phái nhân vật',{exact:true})).toBeVisible({timeout:30000})
 await page.getByRole('tab',{name:'Trang bị',exact:true}).focus()
 await page.keyboard.press('ArrowRight')
 await expect(page.getByRole('tab',{name:'Animation',exact:true})).toBeFocused()
 await page.keyboard.press('End')
 await expect(page.getByRole('tab',{name:'Tinh chỉnh',exact:true})).toHaveAttribute('aria-selected','true')
 await page.keyboard.press('Home')
 await expect(page.getByRole('tab',{name:'Trang bị',exact:true})).toBeFocused()
 await expect(page.locator('.app-header button')).toHaveCount(0)
 await page.getByLabel('Vũ khí thường HSO',{exact:true}).selectOption('0')
 await page.getByRole('tab',{name:'Animation',exact:true}).click()
 await expect(page.getByLabel('Phái nhân vật',{exact:true})).toBeHidden()
 await page.getByLabel('Trạng thái nhân vật',{exact:true}).selectOption('walk')
 await page.getByRole('button',{name:'Xem hướng Sang trái',exact:true}).click()
 await expect(page.locator('.direction-views canvas').first()).toHaveAttribute('data-motion','walk')
 await page.getByRole('button',{name:'Tạm dừng',exact:true}).click()
 await page.getByRole('tab',{name:'Trang bị',exact:true}).click()
 await page.getByLabel('Bộ phận Tóc',{exact:true}).selectOption({label:'Tóc #1'})
 await page.getByRole('tab',{name:'Animation',exact:true}).click()
 await expect(page.getByLabel('Trạng thái nhân vật',{exact:true})).toHaveValue('walk')
 await expect(page.getByRole('button',{name:'Phát animation',exact:true})).toBeVisible()
 await page.getByLabel('Trạng thái nhân vật',{exact:true}).selectOption('attack')
 await page.getByLabel('Kỹ năng tấn công',{exact:true}).selectOption('1')
 await expect(page.locator('#character-effect-stage canvas')).toBeVisible()
 await expect(page.locator('.stage')).toBeHidden()
 await page.getByRole('tab',{name:'Tinh chỉnh',exact:true}).click()
 await expect(page.getByLabel('Tên lớp',{exact:true})).toBeVisible()
 await page.screenshot({path:'/tmp/hso-desktop-character.png',fullPage:true})
 await page.getByRole('link',{name:'Thư viện dữ liệu',exact:true}).click()
 await expect(page.locator('.asset-card').first()).toBeVisible()
 await expect(page.getByRole('button',{name:'Xuất thư viện part',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'Quái vật',exact:false}).click()
 await page.getByLabel('Tìm theo tên hoặc ID',{exact:true}).fill('Ốc sên')
 await page.locator('.asset-card').first().click()
 await page.getByLabel('hp',{exact:true}).fill('999')
 await page.getByRole('button',{name:'Áp dụng nháp',exact:true}).click()
 await expect(page.getByRole('button',{name:'Xuất nháp (1)',exact:true})).toBeVisible()
 await page.screenshot({path:'/tmp/hso-desktop-catalog.png',fullPage:true})
 await page.getByRole('link',{name:'Character Lab',exact:true}).click()
 await expect(page.getByRole('tab',{name:'Tinh chỉnh',exact:true})).toHaveAttribute('aria-selected','true')
 await page.getByRole('tab',{name:'Animation',exact:true}).click()
 await expect(page.getByLabel('Trạng thái nhân vật',{exact:true})).toHaveValue('attack')
 await expect(page.locator('#character-effect-stage canvas')).toBeVisible()
 await page.getByRole('link',{name:'Map',exact:true}).click()
 await expect(page.locator('canvas[data-map-id]')).toHaveAttribute('data-rendered-map-id','0',{timeout:30000})
 await expect(page.getByRole('button',{name:'Xuất map cho Phaser',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Xuất thư viện part',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'Bút tile',exact:true}).click()
 await page.getByRole('button',{name:'Chọn tile 2',exact:true}).click()
 await page.screenshot({path:'/tmp/hso-desktop-map.png',fullPage:true})
 for(const width of [1280,1024]){
  await page.setViewportSize({width,height:900})
  for(const route of ['/maps','/catalog','/character-lab']){
   await page.goto(route)
   await expect(page.locator('.workspace')).toBeVisible({timeout:30000})
   expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${route} at ${width}`).toBe(true)
  }
 }
 expect(errors).toEqual([])
})
