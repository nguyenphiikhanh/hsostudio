test('composite mount and PetTool preserve every native piece/seat and reference exports keep nonnumeric IDs',async({page})=>{
 test.setTimeout(90000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await open(page)
 for(const slot of ['mount','pet']){
  await page.getByLabel('Loại part thiết kế',{exact:true}).selectOption(slot)
  const definitions=await page.evaluate(async()=>{const {companionCatalog}=await import('/src/lib/companions.js');return [...companionCatalog.mounts,...companionCatalog.pets].filter(d=>d.rig?.kind).map(d=>({slot:d.slot,id:d.id}))})
  const candidate=definitions.find(d=>d.slot===slot)
  await page.getByLabel('Mẫu part thiết kế',{exact:true}).selectOption(`${slot}:${candidate.id}`)
  const png=await sample(page)
  const original=JSON.parse((await downloaded(page,()=>page.getByRole('button',{name:'JSON mẫu',exact:true}).click())).bytes)
  expect(String(original.id)).toBe(candidate.id);expect(original.definition.asset.source).toBe(original.template.assets.sheet.source)
  await page.getByLabel('PNG thiết kế sheet',{exact:true}).setInputFiles(file(await recolor(page,png.bytes)))
  await page.getByRole('button',{name:'Preview / cập nhật nháp',exact:true}).click()
  const record=page.locator('.design-draft').last();await expect(record).toBeVisible()
  const doc=JSON.parse((await downloaded(page,()=>record.getByRole('button',{name:'Xuất JSON thiết kế',exact:true}).click())).bytes)
  expect(doc.definition.rig).toEqual(original.definition.rig)
  expect(doc.definition.riderBinding).toEqual(original.definition.riderBinding)
  expect(doc.definition.itemIds).toEqual([]);expect(doc.definition.serverAppearanceStatus).toBe('not-registered')
  expect(doc.definition.asset.density).toBe(original.definition.asset.density)
  await page.getByRole('tab',{name:'Animation',exact:true}).click()
  await page.getByLabel('Trạng thái nhân vật',{exact:true}).selectOption('walk')
  await page.getByRole('tab',{name:'Trang bị',exact:true}).click()
 }
 expect(errors).toEqual([]);await expect(page.getByRole('alert')).toHaveCount(0)
})
