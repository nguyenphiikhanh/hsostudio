const hash=bytes=>createHash('sha256').update(bytes).digest('hex')
async function downloaded(page,action){const p=page.waitForEvent('download');await action();const d=await p;return {name:d.suggestedFilename(),bytes:await fs.readFile(await d.path())}}
async function open(page){await page.goto('/character-lab');await expect(page.getByTestId('part-design-panel')).toBeVisible({timeout:30000});await page.getByTestId('part-design-panel').locator('summary').first().click()}
async function sample(page,resource='sheet'){
 const source=page.locator('.design-source');if(!await source.evaluate(e=>e.open))await source.locator('summary').click()
 return downloaded(page,()=>page.getByLabel(`Tải PNG mẫu ${resource}`,{exact:true}).click())
}
async function recolor(page,bytes,color='#ed1ca6'){
 return Buffer.from(await page.evaluate(async({data,color})=>{
  const blob=new Blob([new Uint8Array(data)],{type:'image/png'}),img=await createImageBitmap(blob)
  const canvas=document.createElement('canvas');canvas.width=img.width;canvas.height=img.height;const ctx=canvas.getContext('2d');ctx.drawImage(img,0,0);ctx.globalCompositeOperation='source-atop';ctx.fillStyle=color;ctx.fillRect(0,0,canvas.width,canvas.height)
  return [...new Uint8Array(await(await new Promise(r=>canvas.toBlob(r,'image/png'))).arrayBuffer())]
 },{data:[...bytes],color}))
}
const file=(bytes,name='new.png')=>({name,mimeType:'image/png',buffer:Buffer.from(bytes)})
const panel=p=>p.getByTestId('part-design-panel')

