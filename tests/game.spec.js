import { test, expect } from '@playwright/test'

test('H5 arena starts, moves in eight directions, pauses, fights and restarts', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Chơi thử H5', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Chơi thử H5 một người' })
  const state = dialog.getByTestId('game-state')
  await expect(dialog.getByRole('button', { name: 'Bắt đầu game' })).toBeVisible({ timeout: 30000 })
  await dialog.getByRole('button', { name: 'Bắt đầu game' }).click()
  await expect(state).toHaveAttribute('data-mode', 'playing')
  await page.keyboard.down('d')
  await page.waitForTimeout(400)
  await page.keyboard.up('d')
  const straight = Number(await state.getAttribute('data-x')) - 640
  expect(straight).toBeGreaterThan(30)
  expect(straight).toBeLessThan(110)
  const before = { x: Number(await state.getAttribute('data-x')), y: Number(await state.getAttribute('data-y')) }
  await page.keyboard.down('d')
  await page.keyboard.down('s')
  await page.waitForTimeout(400)
  await page.keyboard.up('d')
  await page.keyboard.up('s')
  const diagonal = { x: Number(await state.getAttribute('data-x')) - before.x, y: Number(await state.getAttribute('data-y')) - before.y }
  expect(diagonal.x).toBeGreaterThan(20)
  expect(diagonal.y).toBeGreaterThan(20)
  expect(Math.hypot(diagonal.x, diagonal.y)).toBeLessThan(straight * 1.4)
  await page.keyboard.press('Escape')
  await expect(state).toHaveAttribute('data-mode', 'paused')
  const pausedX = await state.getAttribute('data-x')
  await page.keyboard.down('d')
  await page.waitForTimeout(200)
  await page.keyboard.up('d')
  await expect(state).toHaveAttribute('data-x', pausedX)
  await dialog.getByRole('button', { name: 'Tiếp tục game' }).click()
  await expect(state).toHaveAttribute('data-mode', 'playing')
  await dialog.getByRole('button', { name: 'Chơi lại', exact: true }).click()
  await expect(state).toHaveAttribute('data-mode', 'ready')
  await expect(state).toHaveAttribute('data-hp', '100')
  await expect(state).toHaveAttribute('data-x', '640')
  await dialog.getByRole('button', { name: 'Bắt đầu game' }).click()
  for (let i = 0; i < 45; i++) {
    if ((await state.getAttribute('data-mode')) !== 'playing') break
    await page.keyboard.press('Space')
    await page.waitForTimeout(300)
  }
  await expect(state).toHaveAttribute('data-mode', 'won')
  await expect(state).toHaveAttribute('data-kills', '5')
  await page.screenshot({ path: '/tmp/hso-h5-playtest.png', fullPage: true })
  await dialog.getByRole('button', { name: 'Đóng bản chơi thử' }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: 'Chơi thử H5', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Bắt đầu game' })).toBeVisible()
  await page.getByRole('button', { name: 'Đóng bản chơi thử' }).click()
  expect(errors).toEqual([])
})

test('arena obstacles block movement and defeat can be restarted', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Chơi thử H5', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Chơi thử H5 một người' })
  const state = dialog.getByTestId('game-state')
  await dialog.getByRole('button', { name: 'Bắt đầu game' }).click()
  // Reach the left side of the rock at (390, 300), then walk into it.
  await page.keyboard.down('a')
  await page.waitForTimeout(2100)
  await page.keyboard.up('a')
  expect(Number(await state.getAttribute('data-x'))).toBeLessThan(315)
  await page.keyboard.down('w')
  await page.waitForTimeout(830)
  await page.keyboard.up('w')
  await page.keyboard.down('d')
  await page.waitForTimeout(800)
  await page.keyboard.up('d')
  const blocked = Number(await state.getAttribute('data-x'))
  expect(blocked).toBeLessThan(325)
  expect(blocked).toBeGreaterThan(295)
  await page.screenshot({ path: '/tmp/hso-h5-arena.png', fullPage: false })
  await dialog.getByRole('button', { name: 'Chơi lại', exact: true }).click()
  await dialog.getByRole('button', { name: 'Bắt đầu game' }).click()
  await expect(state).toHaveAttribute('data-mode', 'lost', { timeout: 16000 })
  await expect(state).toHaveAttribute('data-hp', '0')
  await dialog.getByRole('button', { name: 'Thử lại', exact: true }).click()
  await expect(state).toHaveAttribute('data-mode', 'ready')
  await expect(state).toHaveAttribute('data-hp', '100')
})
