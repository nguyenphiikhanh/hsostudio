 await expect(page.getByRole('alert')).toContainText('Không tải được dữ liệu map')
 await expect(view).toHaveAttribute('data-map-id','')
 await expect(page.getByRole('button',{name:'Xuất map cho Phaser',exact:true})).toBeDisabled()
