import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'
import { unzipSync, strFromU8 } from 'fflate'

test('trial attack uses original extra poses in four directions and shows actual class skill evidence', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const motion = page.getByLabel('Trạng thái nhân vật', { exact: true })
  await expect(motion).toBeVisible({ timeout: 30000 })
  await motion.selectOption('attack')
  await page.getByRole('button', { name: 'Tạm dừng', exact: true }).click()
  // Reset the paused trial explicitly; autoplay may already have advanced under load.
  await page.getByLabel('Pose tấn công A', { exact: true }).selectOption('4')
  await page.getByLabel('Pose tấn công A', { exact: true }).selectOption('3')
  await expect(page.getByLabel('Đối chiếu tấn công')).toBeVisible()
  const canvases = page.locator('.direction-views canvas')
  await expect(canvases.first()).toHaveAttribute('data-pose', '0')
  const base = await canvases.evaluateAll(cs => cs.map(c => c.toDataURL()))
  await page.getByRole('button', { name: 'Frame tiếp →', exact: true }).click()
  await expect(canvases.first()).toHaveAttribute('data-pose', '3')
  await expect(canvases.first()).toHaveAttribute('data-anchor', '3')
  await expect.poll(() => canvases.evaluateAll(cs => cs.map(c => c.toDataURL()))).not.toEqual(base)
  const posed = await canvases.evaluateAll(cs => cs.map(c => c.toDataURL()))
  posed.forEach((value, index) => expect(value).not.toBe(base[index]))
  await page.getByRole('button', { name: 'Frame tiếp →', exact: true }).click()
  await expect(canvases.first()).toHaveAttribute('data-pose', '4')
  const names = ['Trọng kiếm', 'Đoản kiếm', 'Gậy tự vệ', 'Bắn thường']
  for (let clazz = 0; clazz < 4; clazz++) {
    await page.getByLabel('Phái tấn công', { exact: true }).selectOption(String(clazz))
    await expect(page.getByTestId('attack-evidence')).toContainText(names[clazz])
    await expect(page.getByTestId('attack-evidence')).toContainText('cooldown 1000 ms')
    await expect(page.getByTestId('attack-evidence')).toContainText('performDur 0')
  }
  await page.getByLabel('Kỹ năng tấn công', { exact: true }).selectOption('1')
  await expect(page.getByTestId('attack-evidence')).toContainText('Phát súng công phá')
  await expect(page.getByTestId('attack-evidence')).toContainText('cooldown 2400 ms')
  await page.getByLabel('Pose tấn công A', { exact: true }).selectOption('4')
  await page.getByLabel('Anchor tấn công A', { exact: true }).selectOption('5')
  await page.getByRole('button', { name: 'Frame tiếp →', exact: true }).click()
  await expect(canvases.first()).toHaveAttribute('data-pose', '4')
  await expect(canvases.first()).toHaveAttribute('data-anchor', '5')
  await page.getByRole('button', { name: 'Xem hướng Sang phải', exact: true }).click()
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Xuất cho Phaser', exact: false }).click()
  const files = unzipSync(await fs.readFile(await (await pending).path()))
  const config = JSON.parse(strFromU8(files['character-composition.json']))
  expect(config.preview.motion).toBe('attack')
  expect(config.preview.attackTrial).toMatchObject({ experimental: true, provenance: 'studio-trial', clazz: 3, skillId: 1, preparePose: 4, prepareAnchor: 5 })
  expect(config.preview.attackOptions).toEqual({ experimentalAttack: true, anchorPose: 5 })
  expect(config.layers.find(layer => layer.slot === 'shirt').flipX).toBe(true)
  await page.getByLabel('Tốc độ animation', { exact: true }).selectOption('6')
  const libraryDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Xuất thư viện part', exact: true }).click()
  const library = unzipSync(await fs.readFile(await (await libraryDownload).path()))
  const animations = JSON.parse(strFromU8(library['animations.json']))
  expect(animations.states.attack).toMatchObject({ clazz: 3, skillId: 1, fps: 6, experimental: true, preparePose: 4, prepareAnchor: 5 })
  expect(animations.states.attack.frames.map(frame => [frame.pose, frame.anchorPose])).toEqual([[0, 0], [4, 5], [4, 4], [0, 0]])
  expect(JSON.parse(strFromU8(library['combat.json'])).classes[3].skills[1].name).toBe('Phát súng công phá')
  await page.screenshot({ path: '/tmp/hso-attack-preview.png', fullPage: true })
  await motion.selectOption('idle')
  await motion.selectOption('attack')
  await expect(page.getByLabel('Phái tấn công', { exact: true })).toHaveValue('3')
  await expect(page.getByLabel('Pose tấn công A', { exact: true })).toHaveValue('4')
  await expect(page.getByLabel('Anchor tấn công A', { exact: true })).toHaveValue('5')
  expect(errors).toEqual([])
})
